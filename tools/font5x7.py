def rows(c):
    g = G[c] + ["     "] * (8 - len(G[c]))
    assert len(g) == 8 and all(len(r) == 5 for r in g), c
    return [sum(1 << (6 - i) for i, ch in enumerate(r) if ch == '#') for r in g]
data = []
for code in range(32, 127):
    data += rows(chr(code))
if __name__ == '__main__':
    import sys
    if '--show' in sys.argv:
        for code in range(32, 127):
            print(repr(chr(code)))
            for r in rows(chr(code)): print(''.join('#' if r >> (7 - b) & 1 else '.' for b in range(8)))
    else:
        for i in range(0, len(data), 16):
            print('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
