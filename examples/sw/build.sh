#!/usr/bin/env bash
# Assemble rv32i_test.S and generate ../src/rv32i_rom.veryl (module RiscvTestRom)
# and ../src/rvsoc_rom.veryl (RvTestProg: data at 0x300, for the multi-cycle SoC).
# Needs a RISC-V GNU toolchain (riscv64-unknown-elf-*).
set -euo pipefail
cd "$(dirname "$0")"
P=${CROSS:-riscv64-unknown-elf-}

# rom FILE MODULE NOTE [gcc flags]: assemble rv32i_test.S into a case ROM
rom() {
    local file=$1 mod=$2 note=$3; shift 3
    local T; T=$(mktemp -d)
    ${P}gcc -march=rv32i -mabi=ilp32 -nostdlib -Wl,-Ttext=0 "$@" -o "$T/test.elf" rv32i_test.S
    {
        echo "// generated by examples/sw/build.sh from rv32i_test.S -- do not edit"
        [ -n "$note" ] && echo "// $note"
        echo "module $mod ("
        echo "    i_addr: input  logic<32>,"
        echo "    o_inst: output logic<32>,"
        echo ") {"
        echo "    always_comb {"
        echo "        case i_addr[9:0] {"
        ${P}objdump -d -M no-aliases,numeric "$T/test.elf" | awk -F'\t' '/^ +[0-9a-f]+:\t/ {
            addr = $1; gsub(/[ :]/, "", addr); while (length(addr) < 3) addr = "0" addr;
            hex = $2; gsub(/ /, "", hex); asm = $3; if ($4 != "") asm = asm " " $4; sub(/ *#.*/, "", asm);
            printf "            10'"'"'h%s : o_inst = 32'"'"'h%s; // %s\n", addr, hex, asm }'
        echo "            default: o_inst = 32'h00000013; // nop"
        echo "        }"
        echo "    }"
        echo "}"
    } > "../src/$file"
    rm -rf "$T"
    echo "wrote ../src/$file ($(grep -c "o_inst = 32'h" "../src/$file") entries)"
}
rom rv32i_rom.veryl RiscvTestRom ""
# the multi-cycle SoC has one memory for code and data: the results go to 0x300
rom rvsoc_rom.veryl RvTestProg "the same program with its data at 0x300, for TestRvSoc (examples/src/rvsoc.veryl)" -DDATA=0x300

# Cross-check: run the same program on spike (the RISC-V reference ISS) and
# compare its signature with the $assert values of TestRiscvCore.
if command -v spike > /dev/null; then
    T=$(mktemp -d)
    ${P}gcc -march=rv32i -mabi=ilp32 -nostdlib -DSPIKE -DDATA=0x80001000 \
        -Wl,-N,-Ttext=0x80000000,-Tdata=0x80002000,--no-warn-rwx-segments -o "$T/spike.elf" rv32i_test.S
    spike --isa=rv32i -m0x80000000:0x10000 +signature="$T/sig" +signature-granularity=4 "$T/spike.elf"
    bad=0
    while read -r idx val; do
        got=$(sed -n "$((idx + 1))p" "$T/sig")
        [ "$idx" = 1 ] && got=$(printf '%08x' $((0x$got - 0x80000000)))  # auipc: relative to the load address
        if [ "$got" != "$val" ]; then echo "spike mismatch: dmem[$idx] = $got, testbench expects $val"; bad=1; fi
    done < <(grep -o 'dmem\[[0-9]*\] == 32'"'"'h[0-9a-f]*' ../src/rv32i.veryl | sed -E "s/dmem\[([0-9]+)\] == 32'h/\1 /")
    rm -rf "$T"
    [ $bad = 0 ] && echo "spike agrees with all TestRiscvCore expectations"
    [ $bad = 0 ] || exit 1
fi

# RV32IMA + Zicsr (rv32ima_test.S): the expected values come from spike, so the testbench
# ../src/rvsoc_ima_test.veryl (ROM RvTestProgIma + TestRvSocIma) is generated from its signature
if command -v spike > /dev/null; then
    T=$(mktemp -d)
    ${P}gcc -march=rv32ima_zicsr -mabi=ilp32 -nostdlib -DSPIKE -DDATA=0x80001000 \
        -Wl,-N,-Ttext=0x80000000,-Tdata=0x80002000,--no-warn-rwx-segments -o "$T/spike.elf" rv32ima_test.S
    spike --isa=rv32ima_zicsr -m0x80000000:0x10000 +signature="$T/sig" +signature-granularity=4 "$T/spike.elf"
    ${P}gcc -march=rv32ima_zicsr -mabi=ilp32 -nostdlib -Wl,-Ttext=0 -DDATA=0x400 -o "$T/soc.elf" rv32ima_test.S
    {
        echo "// generated by examples/sw/build.sh from rv32ima_test.S -- do not edit"
        echo "// the program (data at 0x400) and its expected results from spike, for RvSoc's RV32IMA + Zicsr"
        echo "module RvTestProgIma ("
        echo "    i_addr: input  logic<32>,"
        echo "    o_inst: output logic<32>,"
        echo ") {"
        echo "    always_comb {"
        echo "        case i_addr[9:0] {"
        ${P}objdump -d -M no-aliases,numeric "$T/soc.elf" | awk -F'\t' '/^ +[0-9a-f]+:\t/ {
            addr = $1; gsub(/[ :]/, "", addr); while (length(addr) < 3) addr = "0" addr;
            hex = $2; gsub(/ /, "", hex); asm = $3; if ($4 != "") asm = asm " " $4; sub(/ *#.*/, "", asm);
            printf "            10'"'"'h%s : o_inst = 32'"'"'h%s; // %s\n", addr, hex, asm }'
        echo "            default: o_inst = 32'h00000013; // nop"
        echo "        }"
        echo "    }"
        echo "}"
        echo ""
        echo "#[test(test_rvsoc_ima)]"
        echo "module TestRvSocIma {"
        echo "    inst clk: \$tb::clock_gen;"
        echo "    inst rst: \$tb::reset_gen(clk);"
        echo ""
        echo "    var ld      : logic    ;"
        echo "    var ld_we   : logic    ;"
        echo "    var ld_addr : logic<9> ;"
        echo "    var ld_rdata: logic<32>;"
        echo "    var prog    : logic<32>;"
        echo ""
        echo "    inst u_prog: RvTestProgIma ("
        echo "        i_addr: {21'd0, ld_addr, 2'b00},"
        echo "        o_inst: prog                    ,"
        echo "    );"
        echo ""
        echo "    inst dut: RvSoc #(MEM_AW: 9, CPB: 4) ("
        echo "        i_clk: clk, i_rst: rst, i_ld: ld, i_ld_we: ld_we, i_ld_addr: ld_addr, i_ld_wdata: prog, o_ld_rdata: ld_rdata,"
        echo "        i_btn: 3'd0, i_sw: 8'd0, i_rx: 1'b1, o_tx: _, o_led: _, o_xwe: _, o_xaddr: _, o_xdata: _,"
        echo "    );"
        echo ""
        echo "    initial {"
        echo "        ld      = 1;"
        echo "        ld_we   = 1;"
        echo "        ld_addr = 0;"
        echo "        rst.assert();"
        echo "        for _i in 0..256 {"
        echo "            clk.next();"
        echo "            ld_addr = ld_addr + 9'd1;"
        echo "        }"
        echo "        ld_we = 0;"
        echo "        ld    = 0;"
        echo "        clk.next(3000);"
        echo "        ld = 1;"
        # the words the program wrote (spike's signature area ends with unwritten zeros)
        awk '{ w[NR] = $1; if ($1 != "00000000") n = NR } END { for (i = 1; i <= n; i++) printf "        ld_addr = 9'"'"'d%d; clk.next(); $assert(ld_rdata == 32'"'"'h%s, \"word %d\");\n", 256 + i - 1, w[i], i - 1 }' "$T/sig"
        echo "        \$finish();"
        echo "    }"
        echo "}"
    } > ../src/rvsoc_ima_test.veryl
    echo "wrote ../src/rvsoc_ima_test.veryl ($(wc -l < "$T/sig") signature words from spike)"
    rm -rf "$T"
fi
