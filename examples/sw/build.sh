#!/usr/bin/env bash
# Assemble rv32i_test.S and generate ../src/rv32i_rom.veryl (module RiscvTestRom).
# Needs a RISC-V GNU toolchain (riscv64-unknown-elf-*).
set -euo pipefail
cd "$(dirname "$0")"
P=${CROSS:-riscv64-unknown-elf-}
T=$(mktemp -d)
${P}gcc -march=rv32i -mabi=ilp32 -nostdlib -Wl,-Ttext=0 -o "$T/test.elf" rv32i_test.S
${P}objcopy -O binary "$T/test.elf" "$T/test.bin"
{
    echo "// generated by examples/sw/build.sh from rv32i_test.S -- do not edit"
    echo "module RiscvTestRom ("
    echo "    i_addr: input  logic<32>,"
    echo "    o_inst: output logic<32>,"
    echo ") {"
    echo "    always_comb {"
    echo "        case i_addr[9:0] {"
    ${P}objdump -d -M no-aliases,numeric "$T/test.elf" | awk -F'\t' '/^ +[0-9a-f]+:\t/ {
        addr = $1; gsub(/[ :]/, "", addr); while (length(addr) < 3) addr = "0" addr;
        hex = $2; gsub(/ /, "", hex); asm = $3; if ($4 != "") asm = asm " " $4; sub(/ *#.*/, "", asm);
        printf "            10'"'"'h%s : o_inst = 32'"'"'h%s; // %s\n", addr, hex, asm }'
    echo "            default: o_inst = 32'h00000013; // nop"
    echo "        }"
    echo "    }"
    echo "}"
} > ../src/rv32i_rom.veryl
rm -rf "$T"
echo "wrote ../src/rv32i_rom.veryl ($(grep -c "o_inst = 32'h" ../src/rv32i_rom.veryl) entries)"

# Cross-check: run the same program on spike (the RISC-V reference ISS) and
# compare its signature with the $assert values of TestRiscvCore.
if command -v spike > /dev/null; then
    T=$(mktemp -d)
    ${P}gcc -march=rv32i -mabi=ilp32 -nostdlib -DSPIKE -DDATA=0x80001000 \
        -Wl,-N,-Ttext=0x80000000,-Tdata=0x80002000,--no-warn-rwx-segments -o "$T/spike.elf" rv32i_test.S
    spike --isa=rv32i -m0x80000000:0x10000 +signature="$T/sig" +signature-granularity=4 "$T/spike.elf"
    bad=0
    while read -r idx val; do
        got=$(sed -n "$((idx + 1))p" "$T/sig")
        [ "$idx" = 1 ] && got=$(printf '%08x' $((0x$got - 0x80000000)))  # auipc: relative to the load address
        if [ "$got" != "$val" ]; then echo "spike mismatch: dmem[$idx] = $got, testbench expects $val"; bad=1; fi
    done < <(grep -o 'dmem\[[0-9]*\] == 32'"'"'h[0-9a-f]*' ../src/rv32i.veryl | sed -E "s/dmem\[([0-9]+)\] == 32'h/\1 /")
    rm -rf "$T"
    [ $bad = 0 ] && echo "spike agrees with all TestRiscvCore expectations"
    exit $bad
fi
