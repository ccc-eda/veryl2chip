//! Netlist writers: yosys JSON (for yosys / nextpnr) and structural Verilog.

use crate::netlist::*;
use std::collections::HashMap;
use std::fmt::Write;

/// Compact net numbering (2, 3, ...) in order of first appearance.
fn numbering(nl: &Netlist) -> HashMap<u32, u32> {
    let mut m = HashMap::new();
    let mut add = |b: Bit| if let Bit::W(w) = b { let n = m.len() as u32 + 2; m.entry(w).or_insert(n); };
    for p in &nl.ports { p.bits.iter().for_each(|b| add(*b)); }
    for c in &nl.cells { c.conns.iter().for_each(|(_, b)| add(*b)); }
    for (_, bits) in &nl.nets { bits.iter().for_each(|b| add(*b)); }
    m
}

fn esc(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

fn port_dir(p: &str) -> &'static str { if is_out(p) { "output" } else { "input" } }

pub fn to_json(nl: &Netlist) -> String {
    let num = numbering(nl);
    let bit = |b: &Bit| match b {
        Bit::C0 => "\"0\"".to_string(),
        Bit::C1 => "\"1\"".to_string(),
        Bit::W(w) => num[w].to_string(),
    };
    let bits = |v: &[Bit]| format!("[{}]", v.iter().map(bit).collect::<Vec<_>>().join(", "));
    let mut s = String::new();
    writeln!(s, "{{\n  \"creator\": \"veryl-eda {}\",\n  \"modules\": {{", env!("CARGO_PKG_VERSION")).unwrap();
    writeln!(s, "    \"{}\": {{", esc(&nl.name)).unwrap();
    writeln!(s, "      \"attributes\": {{ \"top\": \"00000000000000000000000000000001\" }},").unwrap();
    writeln!(s, "      \"ports\": {{").unwrap();
    let ports: Vec<String> = nl.ports.iter().map(|p| {
        format!("        \"{}\": {{ \"direction\": \"{}\", \"bits\": {} }}", esc(&p.name), if p.dir == Dir::In { "input" } else { "output" }, bits(&p.bits))
    }).collect();
    writeln!(s, "{}\n      }},", ports.join(",\n")).unwrap();
    writeln!(s, "      \"cells\": {{").unwrap();
    let cells: Vec<String> = nl.cells.iter().enumerate().map(|(i, c)| {
        let dirs: Vec<String> = c.conns.iter().map(|(p, _)| format!("\"{}\": \"{}\"", p, port_dir(p))).collect();
        let conns: Vec<String> = c.conns.iter().map(|(p, b)| format!("\"{}\": [{}]", p, bit(b))).collect();
        let params: Vec<String> = c.params.iter().map(|(k, v)| format!("\"{}\": \"{}\"", k, v)).collect();
        format!("        \"$veryl${}\": {{ \"hide_name\": 1, \"type\": \"{}\", \"parameters\": {{ {} }}, \"attributes\": {{}}, \"port_directions\": {{ {} }}, \"connections\": {{ {} }} }}",
            i, c.typ, params.join(", "), dirs.join(", "), conns.join(", "))
    }).collect();
    writeln!(s, "{}\n      }},", cells.join(",\n")).unwrap();
    writeln!(s, "      \"netnames\": {{").unwrap();
    let mut seen = std::collections::HashSet::new();
    let nets: Vec<String> = nl.nets.iter().filter(|(n, _)| seen.insert(n.clone())).map(|(n, b)| {
        format!("        \"{}\": {{ \"hide_name\": 0, \"bits\": {}, \"attributes\": {{}} }}", esc(n), bits(b))
    }).collect();
    writeln!(s, "{}\n      }}\n    }}\n  }}\n}}", nets.join(",\n")).unwrap();
    s
}

/// Structural (gate-level) Verilog, e.g. for gate-level simulation with iverilog.
pub fn to_verilog(nl: &Netlist) -> String {
    let num = numbering(nl);
    let name = |b: &Bit| match b {
        Bit::C0 => "1'b0".to_string(),
        Bit::C1 => "1'b1".to_string(),
        Bit::W(w) => format!("n{}", num[w]),
    };
    let ident = |n: &str| if n.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') { n.to_string() } else { format!("\\{} ", n) };
    let mut s = String::new();
    let decl: Vec<String> = nl.ports.iter().map(|p| {
        format!("{} [{}:0] {}", if p.dir == Dir::In { "input " } else { "output" }, p.bits.len().max(1) - 1, ident(&p.name))
    }).collect();
    writeln!(s, "// generated by veryl-eda\nmodule {} (\n  {}\n);", ident(&nl.name), decl.join(",\n  ")).unwrap();
    let regs: std::collections::HashSet<Bit> = nl.cells.iter().filter(|c| c.is_ff() && !c.typ.starts_with("SB_")).map(|c| c.out()).collect();
    let mut ids: Vec<(&u32, &u32)> = num.iter().collect();
    ids.sort_by_key(|x| x.1);
    for (w, n) in ids { writeln!(s, "  {} n{};", if regs.contains(&Bit::W(*w)) { "reg " } else { "wire" }, n).unwrap(); }
    for p in &nl.ports {
        for (i, b) in p.bits.iter().enumerate() {
            if p.dir == Dir::In { writeln!(s, "  assign {} = {}[{}];", name(b), ident(&p.name), i).unwrap(); }
            else { writeln!(s, "  assign {}[{}] = {};", ident(&p.name), i, name(b)).unwrap(); }
        }
    }
    for (i, c) in nl.cells.iter().enumerate() {
        let g = |p: &str| name(&c.port(p).unwrap());
        let y = name(&c.out());
        match c.typ.as_str() {
            "$_NOT_" => writeln!(s, "  assign {} = ~{};", y, g("A")),
            "$_AND_" => writeln!(s, "  assign {} = {} & {};", y, g("A"), g("B")),
            "$_OR_" => writeln!(s, "  assign {} = {} | {};", y, g("A"), g("B")),
            "$_XOR_" => writeln!(s, "  assign {} = {} ^ {};", y, g("A"), g("B")),
            "$_MUX_" => writeln!(s, "  assign {} = {} ? {} : {};", y, g("S"), g("B"), g("A")),
            t if t.starts_with("SB_") => {
                // iCE40 primitive (simulation models: yosys techlibs/ice40/cells_sim.v)
                let params: Vec<String> = c.params.iter().map(|(k, v)| format!(".{}({}'b{})", k, v.len(), v)).collect();
                let pins: Vec<String> = c.conns.iter().map(|(p, b)| format!(".{}({})", p, name(b))).collect();
                let ps = if params.is_empty() { String::new() } else { format!(" #({})", params.join(", ")) };
                writeln!(s, "  {}{} c{} ({});", t, ps, i, pins.join(", "))
            }
            t => {
                // $_DFF_P_ / $_DFF_PN0_ / $_SDFF_PP1_ ...
                let f: Vec<char> = t.trim_start_matches("$_").trim_start_matches("S").trim_start_matches("DFF_").chars().collect();
                let edge = if f[0] == 'P' { "posedge" } else { "negedge" };
                if c.port("R").is_none() {
                    writeln!(s, "  always @({} {}) {} <= {};", edge, g("C"), y, g("D"))
                } else {
                    let act = if f[1] == 'P' { g("R") } else { format!("!{}", g("R")) };
                    let redge = if f[1] == 'P' { "posedge" } else { "negedge" };
                    let sens = if t.starts_with("$_SDFF") { format!("{} {}", edge, g("C")) } else { format!("{} {} or {} {}", edge, g("C"), redge, g("R")) };
                    writeln!(s, "  always @({}) if ({}) {} <= 1'b{}; else {} <= {};", sens, act, y, f[2], y, g("D"))
                }
            }
        }.unwrap();
    }
    writeln!(s, "endmodule").unwrap();
    s
}
